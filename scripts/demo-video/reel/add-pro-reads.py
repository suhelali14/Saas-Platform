for lang, lines in PRO.items():
    p = HERE / f"story-reel-{lang}.json"
    d = json.load(io.open(p, encoding="utf-8"))
    assert len(d["beats"]) == len(lines)
    d.update({"tts": "elevenlabs", "elevenModel": "eleven_v3", "elevenStability": 0.5, "pad": 0.35})
    for b, line in zip(d["beats"], lines):
        b["sayPro"] = line
        # sanity: spoken words (cues removed) must match caption tokens one to one
        import re
        spoken = re.sub(r"\[[^\]]*\]", " ", line).split()
        if len(spoken) != len(b["cap"].split()):
            print(f"{lang}: word count differs ({len(spoken)} vs {len(b['cap'].split())}): {b['cap'][:40]}")
    json.dump(d, io.open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(lang, "ok")
