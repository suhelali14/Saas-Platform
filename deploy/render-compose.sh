#!/usr/bin/env bash
#
# Writes /srv/clinic/compose.yml from whatever is in /srv/clinic/env/.
#
# The number of clinics changes over time, so the compose file is
# generated rather than hand-maintained: one service per env file, every
# one running the same image with a different entrypoint, env file, port
# and uploads mount. Adding a clinic means dropping in an env file and
# re-running this.
#
# Called by deploy-image.sh and by add-clinic.sh. Safe to run any time --
# it only rewrites the file, it does not restart anything.
set -euo pipefail

# Overridable so this can be exercised against a throwaway directory
# instead of only ever being tested by deploying it.
ROOT="${CLINIC_ROOT:-/srv/clinic}"
ENV_DIR="$ROOT/env"
DATA_DIR="$ROOT/data"
JOBS_DIR="$ROOT/jobs"
OUT="$ROOT/compose.yml"

# The image tag to run. deploy-image.sh writes this after a successful
# pull, so this file is the single record of what is deployed.
IMAGE="$(cat "$ROOT/.image" 2>/dev/null || true)"
if [ -z "$IMAGE" ]; then
  echo "No image recorded in $ROOT/.image -- run deploy-image.sh first." >&2
  exit 1
fi

# Parsed, not sourced. A value containing `&` -- every Neon connection
# string has one -- is truncated to nothing when the shell evaluates it,
# while docker --env-file reads it correctly. PORT happens to survive
# that, but relying on which keys happen to be shell-safe is not a
# property worth depending on.
# Run containers as whoever owns the data directory.
#
# The image defines a `node` user at uid 1000, but the host's deploy
# account is a system user with a different uid -- so a bind-mounted
# uploads directory is either unwritable by the container or unmanageable
# by the deploy user, depending on which one you chown it to. Reading the
# owner here means neither side has to match a number chosen by the other.
if [ -d "$DATA_DIR" ]; then
  RUN_AS="$(stat -c '%u:%g' "$DATA_DIR")"
else
  RUN_AS="$(id -u):$(id -g)"
fi

read_var() {  # read_var <file> <KEY>
  local raw
  raw="$(sed -n "s/^$2=//p" "$1" | head -1)"
  # Strip one layer of surrounding quotes using parameter expansion.
  # No sed backreference: it is the thing that keeps getting eaten by
  # whichever layer writes this file.
  case "$raw" in
    \"*\") raw="${raw#\"}"; raw="${raw%\"}" ;;
    \'*\') raw="${raw#\'}"; raw="${raw%\'}" ;;
  esac
  printf '%s' "$raw"
}

# Per-container memory cap, sized from the machine rather than hardcoded.
#
# The cap exists to stop one busy clinic starving the others. That is a
# real concern with eight clinics on 2 GB; with one clinic on a 512 MB
# droplet there is nobody to starve, and a hard cap only adds a way to be
# killed -- Docker kills a container that reaches its limit, which is
# exactly the mid-consultation death the swap file was added to prevent.
#
# So: no cap on a small box (swap is the safety net there), and a
# computed cap once there is enough RAM for the cap to be the lesser
# risk. Override with CLINIC_MEMORY_LIMIT=300M if you disagree.
# /proc/meminfo rather than `free`: it is always present on Linux, needs
# no package, and -- unlike a failing `free` under `set -e pipefail` --
# a missing file here does not abort the script before the default
# applies. Guarded so this stays runnable off a Linux box for testing.
TOTAL_MB=""
if [ -r /proc/meminfo ]; then
  TOTAL_MB="$(awk '/^MemTotal:/ {printf "%d", $2/1024}' /proc/meminfo 2>/dev/null || true)"
fi
TOTAL_MB="${TOTAL_MB:-1024}"

SERVICE_COUNT="$(find "$ENV_DIR" -maxdepth 1 -name '*.env' 2>/dev/null | wc -l | tr -d ' ')"
[ "${SERVICE_COUNT:-0}" -lt 1 ] && SERVICE_COUNT=1

if [ -n "${CLINIC_MEMORY_LIMIT:-}" ]; then
  MEM_LIMIT="$CLINIC_MEMORY_LIMIT"
elif [ "$TOTAL_MB" -lt 900 ]; then
  MEM_LIMIT=""      # too small to cap safely
else
  # Leave ~300 MB for the OS, Docker and nginx, share the rest.
  CAP=$(( (TOTAL_MB - 300) / SERVICE_COUNT ))
  [ "$CAP" -gt 500 ] && CAP=500
  [ "$CAP" -lt 220 ] && CAP=220
  MEM_LIMIT="${CAP}M"
fi

{
  echo "# GENERATED by deploy/render-compose.sh -- do not edit by hand."
  echo "# Regenerate after adding or removing a clinic."
  echo "# Written $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  echo "services:"
} > "$OUT.tmp"

shopt -s nullglob
ENV_FILES=("$ENV_DIR"/*.env)
shopt -u nullglob

if [ ${#ENV_FILES[@]} -eq 0 ]; then
  echo "No env files in $ENV_DIR -- nothing to render." >&2
  rm -f "$OUT.tmp"
  exit 1
fi

COUNT=0
for env_file in "${ENV_FILES[@]}"; do
  slug="$(basename "$env_file" .env)"
  port="$(read_var "$env_file" PORT)"

  if [ -z "$port" ]; then
    echo "WARNING: $slug has no PORT, skipping" >&2
    continue
  fi

  if [ "$slug" = "provider" ]; then
    service="provider-api"
    command='["node", "apps/provider-api/dist/server.js"]'
    # The console writes provisioning jobs here for the host runner to
    # carry out. This is the ONLY way it can affect the host, and it can
    # ask for exactly one thing -- a clinic -- because nothing on the
    # other side takes a command from the file.
    extra_volume="      - $JOBS_DIR:/srv/clinic/jobs"
  else
    service="clinic-$slug"
    command='["node", "apps/clinic-api/dist/index.js"]'
    extra_volume=""
  fi

  mkdir -p "$DATA_DIR/$slug/uploads"

  # ── This clinic's session store ──────────────────────────────────
  #
  # One Redis per clinic, not one shared. The product's first principle
  # is that a breach of any one thing must not expose every clinic --
  # which is why each has its own database -- and every clinic's live
  # sessions in a single store would undo that for the sake of a
  # container.
  #
  # The network is what makes that real rather than a naming convention.
  # All clinics share one compose file, so without it clinic A's API
  # could reach clinic B's Redis by service name. Each pair gets a
  # private bridge and joins nothing else.
  #
  # No published port: nothing outside this network can reach it, so it
  # needs no password of its own on top.
  #
  # No persistence. Sessions are ephemeral by nature and a restart simply
  # asks everyone to sign in again, which is a far better failure than a
  # stale dump of live credentials surviving on disk.
  if [ "$slug" != "provider" ]; then
    cat >> "$OUT.tmp" <<REDIS
  redis-$slug:
    image: redis:7-alpine
    container_name: redis-$slug
    command: ["redis-server", "--save", "", "--appendonly", "no", "--maxmemory", "32mb", "--maxmemory-policy", "noeviction"]
    networks:
      - net-$slug
    restart: unless-stopped
    stop_grace_period: 5s
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 10s
      timeout: 3s
      retries: 5
    logging:
      driver: json-file
      options:
        max-size: "2m"
        max-file: "2"

REDIS
  fi

  cat >> "$OUT.tmp" <<SERVICE
  $service:
    image: $IMAGE
    command: $command
    # Matches the owner of the bind-mounted uploads directory.
    user: "$RUN_AS"
    container_name: $service
    env_file:
      - $ENV_DIR/$slug.env
    # Bound to loopback only. nginx terminates TLS and proxies in; exposing
    # these publicly would skip both that and its rate limits.
    ports:
      - "127.0.0.1:$port:$port"
    networks:
      - net-$slug
    volumes:
      # Patient scans and lab reports. The app resolves uploads against
      # its working directory (/app), so this mount is what makes them
      # survive a deploy instead of dying with the container.
      - $DATA_DIR/$slug/uploads:/app/uploads
$extra_volume
    restart: unless-stopped
    stop_grace_period: 20s
    logging:
      driver: json-file
      options:
        # Without a cap, container logs fill a 25 GB disk and take the
        # clinic down in a way that looks like an application fault.
        max-size: "10m"
        max-file: "3"
SERVICE

  # Memory cap, only where capping is the lesser risk -- see the top of
  # this script.
  if [ -n "$MEM_LIMIT" ]; then
    cat >> "$OUT.tmp" <<LIMIT
    deploy:
      resources:
        limits:
          memory: $MEM_LIMIT
LIMIT
  fi
  printf '\n' >> "$OUT.tmp"
  COUNT=$((COUNT + 1))
done

# ── Networks ────────────────────────────────────────────────────────
#
# One private bridge per clinic. Compose would otherwise put every
# service on a single default network, where each clinic's API could
# reach every other clinic's session store by name -- which would make
# "one Redis per clinic" a naming convention rather than a boundary.
#
# Declared after the services because a compose file is read whole; the
# order is for whoever opens it.
{
  echo ""
  echo "networks:"
  for env_file in "${ENV_FILES[@]}"; do
    slug="$(basename "$env_file" .env)"
    # Every service that was rendered needs its network declared,
    # including the provider console -- it has no Redis, but it still
    # joins a network, and a reference to one that is never declared
    # makes compose reject the whole file.
    [ -z "$(read_var "$env_file" PORT)" ] && continue
    echo "  net-$slug:"
    echo "    driver: bridge"
  done
} >> "$OUT.tmp"

mv -f "$OUT.tmp" "$OUT"
echo "Rendered $OUT: $COUNT service(s) on $IMAGE"
