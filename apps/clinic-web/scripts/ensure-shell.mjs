/**
 * Writes a placeholder api/_shell.js when there is not one already.
 *
 * The real file is generated from the build output, and a typecheck runs
 * before the build has produced it -- so without this, a clean checkout
 * and CI both fail to compile on a missing module. Which is exactly how
 * the last deployment broke: the file existed on the machine it was
 * written on and nowhere else.
 *
 * Run from `postinstall`, so `npm ci` creates it however the typecheck
 * is later invoked. Putting it only in the `typecheck` npm script was
 * not enough: CI runs `npx tsc -b` directly and never sees that script.
 * This matches how each API's Prisma client is handled -- generated by
 * postinstall, gitignored, with a named CI step as belt and braces.
 *
 * Not committed. A committed copy would be overwritten by every build,
 * leaving the tree permanently dirty and making it easy to commit one
 * build's shell by accident.
 *
 * The placeholder's values are useless on purpose: an empty shell and no
 * directory make the SEO functions serve nothing rather than something
 * wrong, and a real build replaces both.
 */
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { writeShellModule, API_DIR } from './shell-file.mjs';

if (existsSync(resolve(API_DIR, '_shell.js'))) process.exit(0);

writeShellModule({
  shell: '',
  providerApi: '',
  why: 'Placeholder from scripts/ensure-shell.mjs. Replaced by the real build.',
});

console.log('ensure-shell: wrote a placeholder api/_shell.js');
